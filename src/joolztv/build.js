// Builds the UI twice from ui/: dist/modern (browsers) and dist/compat (Chromium 53, LG webOS 4).
// The build FAILS if the old-TV copy would use something Chromium 53 cannot run (see guards below).
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const esbuild = require("esbuild"), acorn = require("acorn");

const ROOT = __dirname, UI = process.env.UI_SRC ? path.resolve(process.env.UI_SRC) : path.join(ROOT, "ui"), PUB = path.join(ROOT, "public"), OUT = process.env.UI_OUT ? path.resolve(process.env.UI_OUT) : path.join(ROOT, "dist");

/* ---------- guards: what Chromium 53 cannot do and no polyfill/transform can fix ---------- */
const JS_FORBIDDEN = [
  [/\bResizeObserver\b/, "ResizeObserver (Chrome 64)"], [/\bWebAssembly\b/, "WebAssembly (Chrome 57)"], [/\bstructuredClone\b/, "structuredClone (Chrome 98)"],
  [/\bqueueMicrotask\b/, "queueMicrotask (Chrome 71)"], [/AbortSignal\.timeout/, "AbortSignal.timeout (Chrome 103)"], [/\bObject\.hasOwn\b/, "Object.hasOwn (Chrome 93)"],
  [/\.at\(\s*-?\d+\s*\)/, "Array/String .at() (Chrome 92)"], [/\brequestIdleCallback\b/, "requestIdleCallback (Chrome 47 flag only on TVs)"], [/\bnew Intl\.(?:ListFormat|RelativeTimeFormat)\b/, "Intl.ListFormat/RelativeTimeFormat"],
  [/\bcrypto\.randomUUID\b/, "crypto.randomUUID (Chrome 92)"], [/\bnavigator\.clipboard\b/, "navigator.clipboard"], [/\bfetch\([^)]*\{[^}]*\bsignal\s*:/, "fetch AbortSignal (Chrome 66)"],
];
const CSS_FORBIDDEN = [
  [/display\s*:\s*(?:inline-)?grid/, "CSS grid (Chrome 57)"], [/(^|[;{\s])grid[-a-z]*\s*:/, "grid-* properties"], [/(^|[;{\s])(?:row-|column-)?gap\s*:/, "gap (Chrome 66 for flex)"],
  [/aspect-ratio\s*:/, "aspect-ratio (Chrome 88)"], [/position\s*:\s*sticky/, "position: sticky (Chrome 56)"], [/(^|[;{\s])inset\s*:/, "inset (Chrome 87)"],
  [/:(?:is|where|has)\(/, ":is/:where/:has"], [/:focus-within|:focus-visible/, ":focus-within / :focus-visible"], [/(?<![-\w])(?:clamp|min|max)\(/, "CSS min()/max()/clamp() (Chrome 79)"],
  [/@container/, "@container queries"], [/color-mix\(|oklch\(|oklab\(/, "modern colour functions"], [/\b\d+d?v[hw]\b/, "dvh/dvw units"], [/\bscroll-behavior\s*:/, "scroll-behavior (Chrome 61)"],
  [/\bobject-position\b.*\bmax-content\b/, "max-content tricks"], [/\bmask(?:-image)?\s*:/, "CSS mask (needs -webkit- on old Chrome)"], [/\bfilter\s*:\s*blur/, "filter: blur (very slow on TVs)"],
];
function stripSupports(css) {                         // backdrop-filter is allowed only inside an @supports block
  let out = "", i = 0;
  while (i < css.length) {
    const j = css.indexOf("@supports", i);
    if (j < 0) { out += css.slice(i); break; }
    out += css.slice(i, j);
    let k = css.indexOf("{", j), depth = 1; k++;
    while (k < css.length && depth) { if (css[k] === "{") depth++; else if (css[k] === "}") depth--; k++; }
    i = k;
  }
  return out;
}
function guardJs(src, name) {
  const bad = JS_FORBIDDEN.filter(([re]) => re.test(src)).map(x => x[1]);
  if (bad.length) throw new Error(name + " uses things Chromium 53 doesn't have: " + bad.join(", "));
}
function guardCss(src, name) {
  const css = src.replace(/\/\*[\s\S]*?\*\//g, ""), outside = stripSupports(css);
  const bad = CSS_FORBIDDEN.filter(([re]) => re.test(outside)).map(x => x[1]);
  if (/backdrop-filter/.test(outside)) bad.push("backdrop-filter outside @supports (Chrome 76)");
  if (bad.length) throw new Error(name + " uses CSS Chromium 53 doesn't have: " + bad.join(", "));
}
function guardOutput(js) {                            // the converted bundle must parse as ES2015 (Chrome 53 level): no async/await, **, spread in objects, ?., ??
  try { acorn.parse(js, { ecmaVersion: 2015, sourceType: "script" }); }
  catch (e) { throw new Error("compat bundle is not valid ES2015 (" + e.message + ")"); }
}

/* ---------- read the page ---------- */
const html = fs.readFileSync(path.join(UI, "index.html"), "utf8");
const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map(m => m[1]);
const styles = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)].map(m => m[1]);
const local = scripts.filter(s => s !== "config.js");           // config.js is generated by the server at run time
const read = f => fs.readFileSync(path.join(UI, f), "utf8");

function build(kind) {
  const compat = kind === "compat", dir = path.join(OUT, kind);
  fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir, { recursive: true });
  let js = local.map(f => { const s = read(f); if (compat) guardJs(s, f); return "/* " + f + " */\n" + s; }).join("\n;\n");
  if (compat) js = fs.readFileSync(require.resolve("core-js-bundle/minified.js"), "utf8") + "\n;\n" + js;     // adds the missing browser APIs
  const out = esbuild.transformSync(js, { loader: "js", target: compat ? "chrome53" : "es2020", minify: true, legalComments: "none" }).code;
  if (compat) guardOutput(out);
  let css = styles.map(f => { const s = read(f); if (compat) guardCss(s, f); return s; }).join("\n");
  css = esbuild.transformSync(css, { loader: "css", target: compat ? "chrome53" : "es2020", minify: true }).code;
  const hash = crypto.createHash("sha1").update(out + css).digest("hex").slice(0, 8);
  fs.writeFileSync(path.join(dir, "app.js"), out); fs.writeFileSync(path.join(dir, "app.css"), css);
  let page = html.replace(/<script src="(?!config\.js)[^"]+"><\/script>\n?/g, "").replace(/<link rel="stylesheet" href="[^"]+">\n?/g, "")
    .replace("</head>", '<link rel="stylesheet" href="app.css?v=' + hash + '">\n</head>').replace("</body>", '<script src="app.js?v=' + hash + '"></script>\n</body>');
  fs.writeFileSync(path.join(dir, "index.html"), page);
  if (fs.existsSync(PUB)) for (const f of fs.readdirSync(PUB)) fs.copyFileSync(path.join(PUB, f), path.join(dir, f));
  console.log(kind + ": app.js " + (out.length / 1024).toFixed(0) + " KB, app.css " + (css.length / 1024).toFixed(0) + " KB, build " + hash);
}
for (const k of ["modern", "compat"]) build(k);
module.exports = { guardJs, guardCss, guardOutput };
