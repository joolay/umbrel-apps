#!/usr/bin/env python3
"""Builds the ONE template file every JoolzApp loads: templates/glass/jz.js.

jz.js = glass.css + floatbar.css (injected as styles) + floatbar.js, install-help.js, installbtn.js,
linkstatus.js, theme-global.js, draghandle.js, quick-ui.js. Edit the source files, then run:

  python3 templates/glass/build.py            build jz.js and copy it into every app that uses it
  python3 templates/glass/build.py --check    exit 1 if jz.js or any app's copy is out of date (for CI)

An app that uses it has `<script src="jz.js"></script>` FIRST in <head> (before its own CSS) and a `jz.js` in its public/ folder.
Options go on that tag: data-claude (Claude handshake icon), data-portal="." or data-portal="https://..." (global theme address).
"""
import glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
rd = lambda p: open(p, encoding='utf-8').read()
JS = ['floatbar.js', os.path.join(ROOT, 'src/portal-admin/public/install-help.js'), 'installbtn.js', 'linkstatus.js', 'theme-global.js', 'draghandle.js', 'quick-ui.js']

def build():
    out = ['/* JoolzApp template bundle (generated by templates/glass/build.py: do not edit; edit the source files and rebuild). */',
           '(function () { "use strict"; window.JZ_SCRIPT = document.currentScript;',
           '  var d = document, h = d.head || d.documentElement;',
           '  function css(id, text, at) { var s = d.createElement("style"); s.id = id; s.textContent = text; (at || h).appendChild(s); }',
           '  /* Glass goes in right here (first in <head>) so the app\'s own CSS, loaded after, wins; the top bar CSS goes last so it wins over the app\'s. */',
           '  css("jz-glass", %s);' % json.dumps(rd(os.path.join(HERE, 'glass.css'))),
           '  var BAR = %s;' % json.dumps(rd(os.path.join(HERE, 'floatbar.css'))),
           '  function bar() { if (!d.getElementById("jz-bar")) css("jz-bar", BAR); }',
           '  if (d.body) bar(); else { var mo = new MutationObserver(function () { if (d.body) { mo.disconnect(); bar(); } }); mo.observe(d.documentElement, { childList: true }); d.addEventListener("DOMContentLoaded", bar); }',
           '})();']
    for f in JS:
        p = f if os.path.isabs(f) else os.path.join(HERE, f)
        out.append('\n/* ---- %s ---- */\n%s' % (os.path.basename(p), rd(p).rstrip()))
    return '\n'.join(out) + '\n'

def users():
    return sorted(os.path.dirname(p) for p in glob.glob(os.path.join(ROOT, 'src', '*', 'public', 'jz.js')))

if __name__ == '__main__':
    b = build(); target = os.path.join(HERE, 'jz.js'); bad = []
    if '--check' in sys.argv:
        if not os.path.exists(target) or rd(target) != b: bad.append(target)
        bad += [os.path.join(u, 'jz.js') for u in users() if rd(os.path.join(u, 'jz.js')) != b]
        print('out of date:', *bad, sep='\n  ') if bad else print('template bundle ok (%d apps)' % len(users())); sys.exit(1 if bad else 0)
    open(target, 'w', encoding='utf-8').write(b)
    for u in users(): open(os.path.join(u, 'jz.js'), 'w', encoding='utf-8').write(b)
    print('built jz.js (%d bytes), copied to %d apps' % (len(b), len(users())))
